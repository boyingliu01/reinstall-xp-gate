import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import {
  backupThenRemove, hasXpGateMarker, scanSkillResidue, pruneDeadRoots,
  contentHashes, MARKER_SCAN_LIMIT,
} from '../scripts/lib/residue.mjs';
import { hashTree, rmrf, isFile } from '../scripts/lib/util.mjs';

function tmpDir(t, prefix = 'xgr-residue-') {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), prefix));
  t.after(() => rmrf(dir));
  return dir;
}

function fakePkg(t, names) {
  const pkg = tmpDir(t, 'xgr-pkg-');
  for (const name of names) {
    fs.mkdirSync(path.join(pkg, 'skills', name), { recursive: true });
    fs.writeFileSync(path.join(pkg, 'skills', name, 'SKILL.md'), '# ' + name + '\n');
  }
  return pkg;
}

// --- backupThenRemove: every call in reinstall deletes user data ------------

test('backupThenRemove copies a directory into residue/ then deletes the original', (t) => {
  const runDir = tmpDir(t);
  const victim = tmpDir(t);
  fs.writeFileSync(path.join(victim, 'a.txt'), 'important');
  fs.mkdirSync(path.join(victim, 'nested'));
  fs.writeFileSync(path.join(victim, 'nested', 'b.txt'), 'deep');

  backupThenRemove(victim, runDir, path.join('skills', 'DSH-thing'));

  assert.equal(fs.existsSync(victim), false, 'original must be gone');
  const backup = path.join(runDir, 'residue', 'skills', 'DSH-thing');
  assert.equal(fs.readFileSync(path.join(backup, 'a.txt'), 'utf8'), 'important');
  assert.equal(fs.readFileSync(path.join(backup, 'nested', 'b.txt'), 'utf8'), 'deep');
});

test('backupThenRemove handles a single file entry', (t) => {
  const runDir = tmpDir(t);
  const victim = tmpDir(t);
  const file = path.join(victim, 'pre-commit');
  fs.writeFileSync(file, '#!/bin/sh\n# xp-gate');

  backupThenRemove(file, runDir, path.join('project-hooks', 'pre-commit'), true);

  assert.equal(fs.existsSync(file), false);
  assert.equal(
    fs.readFileSync(path.join(runDir, 'residue', 'project-hooks', 'pre-commit'), 'utf8'),
    '#!/bin/sh\n# xp-gate'
  );
});

test('backupThenRemove creates nested label directories', (t) => {
  const runDir = tmpDir(t);
  const victim = tmpDir(t);
  fs.writeFileSync(path.join(victim, 'f'), 'x');

  // Labels like "templates/<agent>/git-hooks-template" are three levels deep.
  assert.doesNotThrow(() => backupThenRemove(victim, runDir, 'templates/Qoder/git-hooks-template'));
  assert.ok(isFile(path.join(runDir, 'residue', 'templates', 'Qoder', 'git-hooks-template', 'f')));
});

// --- hasXpGateMarker: guards against deleting unrelated directories --------

test('hasXpGateMarker finds the marker in a nested file', (t) => {
  const dir = tmpDir(t);
  fs.mkdirSync(path.join(dir, 'hooks'));
  fs.writeFileSync(path.join(dir, 'hooks', 'pre-commit'), '#!/bin/sh\n# generated by xp-gate\n');

  assert.equal(hasXpGateMarker(dir), true);
});

test('hasXpGateMarker matches case-insensitively', (t) => {
  const dir = tmpDir(t);
  fs.writeFileSync(path.join(dir, 'f'), 'XP-GATE');

  assert.equal(hasXpGateMarker(dir), true);
});

test('hasXpGateMarker returns false for an unrelated directory', (t) => {
  const dir = tmpDir(t);
  fs.writeFileSync(path.join(dir, 'mine.sh'), 'echo hello\n');

  // This is the whole safety property: no marker means do NOT delete.
  assert.equal(hasXpGateMarker(dir), false);
});

test('hasXpGateMarker returns false for an empty or missing directory', (t) => {
  const dir = tmpDir(t);
  assert.equal(hasXpGateMarker(dir), false);
  assert.equal(hasXpGateMarker('/no/such/dir'), false);
});

test('hasXpGateMarker tolerates binary files without throwing', (t) => {
  const dir = tmpDir(t);
  fs.writeFileSync(path.join(dir, 'binary.bin'), Buffer.from([0x00, 0xff, 0xfe]));
  fs.writeFileSync(path.join(dir, 'note.md'), 'xp-gate');

  assert.equal(hasXpGateMarker(dir), true);
});

test('hasXpGateMarker caps how many files it inspects', (t) => {
  const dir = tmpDir(t);
  // Marker sits beyond the cap; the bounded scan must return false rather than
  // walking an unbounded tree.
  for (let i = 0; i < MARKER_SCAN_LIMIT + 5; i += 1) {
    fs.writeFileSync(path.join(dir, 'f' + String(i).padStart(3, '0') + '.txt'), 'plain');
  }
  fs.writeFileSync(path.join(dir, 'zzz-last.txt'), 'xp-gate');

  assert.equal(hasXpGateMarker(dir), false);
});

// --- scanSkillResidue: decides what is safe to delete ----------------------

test('scanSkillResidue separates byte-identical copies from user-modified ones', (t) => {
  const pkg = fakePkg(t, ['alpha']);
  const root = tmpDir(t);
  const srcHash = hashTree(path.join(pkg, 'skills', 'alpha'));

  fs.cpSync(path.join(pkg, 'skills', 'alpha'), path.join(root, 'alpha'), { recursive: true });
  fs.cpSync(path.join(pkg, 'skills', 'alpha'), path.join(root, 'beta'), { recursive: true });
  fs.writeFileSync(path.join(root, 'beta', 'SKILL.md'), '# edited\n');

  const oldHashes = new Map([['alpha', srcHash], ['beta', srcHash]]);
  const { identical, modified } = scanSkillResidue([{ agent: 'A', dir: root }], oldHashes);

  assert.deepEqual(identical.map((r) => r.name), ['alpha']);
  assert.deepEqual(modified.map((r) => r.name), ['beta']);
});

test('scanSkillResidue ignores directories that are not in the old package', (t) => {
  const root = tmpDir(t);
  fs.mkdirSync(path.join(root, 'unrelated'));
  fs.writeFileSync(path.join(root, 'unrelated', 'x'), 'y');

  const { identical, modified } = scanSkillResidue([{ agent: 'A', dir: root }], new Map());
  assert.deepEqual(identical, []);
  assert.deepEqual(modified, []);
});

test('scanSkillResidue skips unreadable roots', () => {
  const result = scanSkillResidue([{ agent: 'A', dir: '/no/such/root' }], new Map([['alpha', 'deadbeef']]));
  assert.deepEqual(result, { identical: [], modified: [] });
});

// --- pruneDeadRoots: deletes only exact matches ----------------------------

test('pruneDeadRoots removes only copies identical to the published package', (t) => {
  const pkg = fakePkg(t, ['alpha']);
  const root = tmpDir(t);

  fs.cpSync(path.join(pkg, 'skills', 'alpha'), path.join(root, 'alpha'), { recursive: true });
  fs.cpSync(path.join(pkg, 'skills', 'alpha'), path.join(root, 'beta'), { recursive: true });
  fs.writeFileSync(path.join(root, 'beta', 'SKILL.md'), '# user edit\n');

  const removed = pruneDeadRoots(pkg, [{ agent: 'A', dir: root }]);

  assert.equal(removed, 1);
  assert.equal(fs.existsSync(path.join(root, 'alpha')), false);
  // A modified copy is user data -- it must survive.
  assert.equal(fs.existsSync(path.join(root, 'beta')), true);
});

test('pruneDeadRoots also removes a stray xp-gate-reinstall copy', (t) => {
  const pkg = fakePkg(t, ['alpha']);
  const root = tmpDir(t);
  fs.mkdirSync(path.join(root, 'xp-gate-reinstall'));
  fs.writeFileSync(path.join(root, 'xp-gate-reinstall', 'SKILL.md'), '# self\n');

  const removed = pruneDeadRoots(pkg, [{ agent: 'A', dir: root }]);

  assert.equal(removed, 1);
  assert.equal(fs.existsSync(path.join(root, 'xp-gate-reinstall')), false);
});

test('pruneDeadRoots does nothing when the package has no skills', (t) => {
  const root = tmpDir(t);
  const pkg = tmpDir(t, 'xgr-empty-pkg-');

  assert.equal(pruneDeadRoots(pkg, [{ agent: 'A', dir: root }]), 0);
});

test('pruneDeadRoots never touches unrelated directories', (t) => {
  const pkg = fakePkg(t, ['alpha']);
  const root = tmpDir(t);
  fs.mkdirSync(path.join(root, 'my-own-skill'));
  fs.writeFileSync(path.join(root, 'my-own-skill', 'SKILL.md'), '# mine\n');

  pruneDeadRoots(pkg, [{ agent: 'A', dir: root }]);

  assert.equal(fs.existsSync(path.join(root, 'my-own-skill')), true);
});

// --- contentHashes --------------------------------------------------------

test('contentHashes maps skill names to directory hashes', (t) => {
  const pkg = fakePkg(t, ['alpha', 'beta']);
  const hashes = contentHashes(pkg);

  assert.deepEqual([...hashes.keys()].sort(), ['alpha', 'beta']);
  assert.match(hashes.get('alpha'), /^[a-f0-9]{64}$/);
});

test('contentHashes returns an empty map for a package without skills/', (t) => {
  assert.equal(contentHashes(tmpDir(t)).size, 0);
  assert.equal(contentHashes('/no/such/pkg').size, 0);
});
